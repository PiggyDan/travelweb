/**
 * MOCK DATA — read only through `services/tour-service.ts`.
 * Shape matches the planned `GET /tours/{slug}` API response.
 * Prices, dates and availability are illustrative.
 */

function usd(amount: number) {
  return { amount, currency: "USD" as const };
}

function departure(
  id: string,
  startDate: string,
  durationDays: number,
  price: number,
  status: DepartureStatus = "available",
  seatsLeft?: number,
): TourDate {
  const [y, m, d] = startDate.split("-").map(Number);
  const end = new Date(Date.UTC(y, m - 1, d + durationDays - 1));
  return {
    id,
    startDate,
    endDate: end.toISOString().slice(0, 10),
    price: usd(price),
    status,
    seatsLeft,
  };
}

